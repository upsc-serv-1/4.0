PKEY_CSV_PATH = os.path.join(DOWNLOADS_DIR, "Supabase Snippet Untitled query (1).csv")
FKEY_CSV_PATH = os.path.join(DOWNLOADS_DIR, "Supabase Snippet Untitled query (2).csv")
INDEX_CSV_PATH = os.path.join(DOWNLOADS_DIR, "Supabase Snippet Untitled query.csv")
MIGRATIONS_DIR = r"c:\Users\Dr. Yogesh\Videos\APP FOLDER - V1 - Copy\app\frontend-noji-2.6.2\3\pilot pro 10.2\supabase\migrations"
